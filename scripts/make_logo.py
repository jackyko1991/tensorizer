"""Generate the Tensorizer logo: a rank-3 tensor T_ijk drawn as an isometric 3x3x3 block of cells,
with one amber cell standing for a single element.

    python scripts/make_logo.py

Writes (gaps between cells are transparent, so both work on any background):
    frontend/public/favicon.svg     blue cells for light backgrounds; switches to the light palette
                                    automatically when the browser/OS is in dark mode
    frontend/public/logo-light.svg  light cells for dark or coloured backgrounds (the blue banner)
"""

from __future__ import annotations

import math
from pathlib import Path

N, U, GAP = 3, 10.0, 0.09  # cells per edge, cell size, inset fraction that opens the transparent gaps
OUT = Path(__file__).resolve().parents[1] / "frontend" / "public"

BLUE = {"top": "#60a5fa", "left": "#2563eb", "right": "#1e40af"}
LIGHT = {"top": "#ffffff", "left": "#dbeafe", "right": "#93c5fd"}
AMBER = {"top": "#fcd34d", "left": "#f59e0b", "right": "#b45309"}

EX = (math.cos(math.pi / 6) * U, 0.5 * U)
EY = (-math.cos(math.pi / 6) * U, 0.5 * U)
EZ = (0.0, -U)


def project(x: float, y: float, z: float) -> tuple[float, float]:
    return (x * EX[0] + y * EY[0] + z * EZ[0], x * EX[1] + y * EY[1] + z * EZ[1])


def faces() -> list[tuple[str, list[tuple[float, float, float]], bool]]:
    """Visible cell faces (top z=N, right x=N, left y=N); the front-top corner cell is highlighted."""
    out = []
    for a in range(N):
        for b in range(N):
            hi = a == N - 1 and b == N - 1
            out.append(("top", [(a, b, N), (a + 1, b, N), (a + 1, b + 1, N), (a, b + 1, N)], hi))
            out.append(("right", [(N, a, b), (N, a + 1, b), (N, a + 1, b + 1), (N, a, b + 1)], hi))
            out.append(("left", [(a, N, b), (a + 1, N, b), (a + 1, N, b + 1), (a, N, b + 1)], hi))
    return out


def inset(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    cx = sum(p[0] for p in points) / len(points)
    cy = sum(p[1] for p in points) / len(points)
    return [(x + (cx - x) * GAP, y + (cy - y) * GAP) for x, y in points]


def svg(palette: dict[str, str], dark_palette: dict[str, str] | None = None) -> str:
    polys = [(face, [project(*c) for c in corners], hi) for face, corners, hi in faces()]
    xs = [x for _, pts, _ in polys for x, _ in pts]
    ys = [y for _, pts, _ in polys for _, y in pts]
    side = max(max(xs) - min(xs), max(ys) - min(ys)) + 4
    ox = (side - (max(xs) - min(xs))) / 2 - min(xs)
    oy = (side - (max(ys) - min(ys))) / 2 - min(ys)

    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {side:.1f} {side:.1f}"'
        ' role="img" aria-label="Tensorizer">',
        "  <title>Tensorizer</title>",
        "  <!-- A rank-3 tensor T_ijk drawn as a 3x3x3 block of cells; the amber cell is one element. -->",
        "  <!-- Generated by scripts/make_logo.py -->",
    ]
    css = [f".{f}{{fill:{c}}}" for f, c in palette.items()] + [f".h{f}{{fill:{c}}}" for f, c in AMBER.items()]
    if dark_palette:
        css.append(
            "@media (prefers-color-scheme: dark){" + "".join(f".{f}{{fill:{c}}}" for f, c in dark_palette.items()) + "}"
        )
    lines.append(f"  <style>{''.join(css)}</style>")
    for face, pts, hi in polys:
        d = " ".join(f"{x + ox:.2f},{y + oy:.2f}" for x, y in inset(pts))
        lines.append(f'  <polygon class="{"h" if hi else ""}{face}" points="{d}"/>')
    lines += ["</svg>", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    (OUT / "favicon.svg").write_text(svg(BLUE, dark_palette=LIGHT), encoding="utf-8")
    (OUT / "logo-light.svg").write_text(svg(LIGHT), encoding="utf-8")
    print("wrote favicon.svg and logo-light.svg")
