r"""Physics → tensor translation.

A neutral kaon is a two-state system in the strangeness basis (K⁰, K̄⁰). Because it decays, its evolution is
generated by an effective non-Hermitian Hamiltonian

    i dψ/dt = H ψ,      H = M − iΓ/2,      M = M†, Γ = Γ† ≥ 0      (2 × 2 complex).

Its eigenstates are the short- and long-lived kaons K_S and K_L with eigenvalues λ = m − iΓ/2. In the
CPLEAR convention, with ε measuring CP violation and δ CPT violation (ε_S = ε + δ, ε_L = ε − δ),

    K_S ∝ (1 + ε_S) K⁰ + (1 − ε_S) K̄⁰,      K_L ∝ (1 + ε_L) K⁰ − (1 − ε_L) K̄⁰,

so H = V Λ V⁻¹ with V = [K_S K_L] and Λ = diag(λ_S, λ_L), and the evolution operator is

    U_{ab}(t) = V_{ai} e^{−iλ_i t} [V⁻¹]_{ib}      (i summed),      P(b → a, t) = |U_{ab}(t)|².

The common mass m_K only adds a global phase and is left out (λ_{S,L} = ∓Δm/2 − iΓ_{S,L}/2).
"""

import torch


def eigenvectors(eps: torch.Tensor, delta: torch.Tensor) -> torch.Tensor:
    r"""V_{ai}: columns K_S, K_L in the (K⁰, K̄⁰) basis, normalised.   eps, delta: (...) → (..., 2, 2) complex"""
    eps, delta = (torch.as_tensor(x, dtype=torch.complex128) for x in (eps, delta))
    e_s, e_l = eps + delta, eps - delta
    k_s = torch.stack([1 + e_s, 1 - e_s], dim=-1)  # (..., 2)
    k_l = torch.stack([1 + e_l, -(1 - e_l)], dim=-1)
    v = torch.stack([k_s, k_l], dim=-1)  # (..., a, i)
    return v / torch.linalg.vector_norm(v, dim=-2, keepdim=True)


def eigenvalues(dm: float, gamma_s: float, gamma_l: float) -> torch.Tensor:
    r"""λ_i = m_i − iΓ_i/2 for i = S, L (common mass removed): (2,) complex"""
    return torch.tensor([-dm / 2 - 0.5j * gamma_s, dm / 2 - 0.5j * gamma_l], dtype=torch.complex128)


def hamiltonian(dm: float, gamma_s: float, gamma_l: float, eps: torch.Tensor, delta: torch.Tensor) -> torch.Tensor:
    r"""H_{ab} = V_{ai} λ_i [V⁻¹]_{ib}   (i summed).   → (..., 2, 2) complex, one H per (ε, δ)"""
    v = eigenvectors(eps, delta)
    lam = eigenvalues(dm, gamma_s, gamma_l).to(v.device)
    return torch.einsum("...ai,i,...ib->...ab", v, lam, torch.linalg.inv(v))


def evolution(h: torch.Tensor, t: torch.Tensor) -> torch.Tensor:
    r"""U_{tab} = V_{ai} e^{−iλ_i t} [V⁻¹]_{ib} = [e^{−iHt}]_{ab}.   h: (B, 2, 2), t: (T,) → (B, T, 2, 2)"""
    lam, v = torch.linalg.eig(h)  # (B, 2), (B, 2, 2)
    phase = torch.exp(-1j * lam[:, None, :] * t[None, :, None])  # (B, T, i)
    return torch.einsum("bxi,bti,biy->btxy", v, phase, torch.linalg.inv(v))


def probabilities(u: torch.Tensor) -> torch.Tensor:
    r"""P(b → a, t) = |U_{ab}(t)|²: index [..., t, a (final), b (initial)], 0 = K⁰, 1 = K̄⁰."""
    return u.abs() ** 2


def decay_matrix(h: torch.Tensor) -> torch.Tensor:
    r"""Γ = i(H − H†): Hermitian and positive semi-definite if probability only leaks out (unitarity)."""
    return 1j * (h - h.conj().transpose(-1, -2))


def kabir_asymmetry(p: torch.Tensor) -> torch.Tensor:
    r"""A_T(t) = [P(K̄⁰→K⁰) − P(K⁰→K̄⁰)] / [P(K̄⁰→K⁰) + P(K⁰→K̄⁰)]: T violation (≈ 4 Re ε)."""
    forward, backward = p[..., 0, 1], p[..., 1, 0]
    return (forward - backward) / (forward + backward)


def cpt_asymmetry(p: torch.Tensor) -> torch.Tensor:
    r"""A_CPT(t) = [P(K̄⁰→K̄⁰) − P(K⁰→K⁰)] / [P(K̄⁰→K̄⁰) + P(K⁰→K⁰)]: zero whenever CPT holds."""
    anti, kaon = p[..., 1, 1], p[..., 0, 0]
    return (anti - kaon) / (anti + kaon)


def flavour_asymmetry(p: torch.Tensor) -> torch.Tensor:
    r"""[P(K⁰→K⁰) − P(K⁰→K̄⁰)] / [sum] = 2 e^{−Γ̄t} cos(Δm t) / (e^{−Γ_S t} + e^{−Γ_L t}) without CP violation."""
    same, flipped = p[..., 0, 0], p[..., 1, 0]
    return (same - flipped) / (same + flipped)


def pipi_amplitude(v: torch.Tensor, eta: torch.Tensor) -> torch.Tensor:
    r"""Row vector a_b with a·K_S = 1 and a·K_L = η₊₋:  a_b = (1, η)_i [V⁻¹]_{ib}.   → (B, 2) complex"""
    eta = torch.as_tensor(eta, dtype=torch.complex128, device=v.device)
    ones = torch.ones_like(eta)
    return torch.einsum("bi,bix->bx", torch.stack([ones, eta], dim=-1), torch.linalg.inv(v))
