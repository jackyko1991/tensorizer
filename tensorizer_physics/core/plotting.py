"""White-theme matplotlib defaults and GIF/PNG writers shared by every plot.py."""

from __future__ import annotations

import csv
import math
import os
import time
from pathlib import Path
from typing import Callable

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.animation import FuncAnimation, PillowWriter  # noqa: E402

from .progress import bar, report  # noqa: E402
from .runtime import fast_mode  # noqa: E402

MAX_FRAMES = 120
ACCENT = ["#2563eb", "#dc2626", "#16a34a", "#9333ea", "#ea580c", "#0891b2", "#db2777", "#65a30d"]

plt.rcParams.update(
    {
        "figure.facecolor": "white",
        "axes.facecolor": "white",
        "axes.edgecolor": "#9ca3af",
        "axes.grid": True,
        "grid.color": "#e5e7eb",
        "axes.prop_cycle": matplotlib.cycler(color=ACCENT),
        "font.size": 10,
        "axes.titlesize": 11,
    }
)


MAX_CSV_ROWS = 10_000
MAX_SERIES_POINTS = 1_000  # longer series keep every k-th point (k noted in the header)


def export_plot_data(fig: plt.Figure, image_path: Path) -> Path | None:
    """Write the numbers drawn in the figure (its final frame) next to the image as <stem>_plot_data.csv.

    One row per plotted point: panel (axes title), series (line or scatter label) and its coordinates; each panel's
    axis labels (which carry the units) are listed once in the # header.
    Images and meshes are left out (only lines and point collections). Returns the
    path, or None when the figure draws no lines or points."""
    rows: list[list] = []
    axes_labels: dict[str, str] = {}
    thinned: list[str] = []

    def add(title, name, xs, ys, zs):
        k = max(1, math.ceil(len(xs) / MAX_SERIES_POINTS))
        if k > 1:
            thinned.append(name)
        for x, y, z in list(zip(xs, ys, zs))[::k]:
            rows.append([title, name, x, y, z])

    for i, ax in enumerate(fig.axes):
        title = ax.get_title() or f"panel {i + 1}"
        xl, yl = ax.get_xlabel(), ax.get_ylabel()
        zl = ax.get_zlabel() if hasattr(ax, "get_zlabel") else ""
        axes_labels.setdefault(title, f"x = {xl or '-'}; y = {yl or '-'}" + (f"; z = {zl}" if zl else ""))
        for k, line in enumerate(ax.get_lines()):
            label = line.get_label()
            name = label if label and not label.startswith("_") else f"line {k + 1}"
            data3 = getattr(line, "_verts3d", None)
            if data3 is not None:  # mpl_toolkits 3D line
                xs, ys, zs = (list(map(float, v)) for v in data3)
            else:
                xs = [float(v) for v in line.get_xdata()]
                ys = [float(v) for v in line.get_ydata()]
                zs = [""] * len(xs)
            add(title, name, xs, ys, zs)
        for k, coll in enumerate(ax.collections):
            offsets3 = getattr(coll, "_offsets3d", None)
            if offsets3 is not None:  # 3D scatter
                xs, ys, zs = (list(map(float, v)) for v in offsets3)
            else:
                offs = coll.get_offsets()
                if offs is None or len(offs) == 0 or getattr(offs, "ndim", 2) != 2:
                    continue
                xs, ys, zs = [float(v) for v in offs[:, 0]], [float(v) for v in offs[:, 1]], [""] * len(offs)
            label = coll.get_label()
            name = label if label and not label.startswith("_") else f"points {k + 1}"
            add(title, name, xs, ys, zs)
        if len(rows) > MAX_CSV_ROWS:
            break
    if not rows:
        return None
    path = Path(image_path).with_name(f"{Path(image_path).stem}_plot_data.csv")
    tmp = _tmp_path(path)
    with tmp.open("w", newline="", encoding="utf-8") as f:
        f.write(f"# Numbers drawn in the final frame of {Path(image_path).name}: lines and point series per panel.\n")
        f.write("# Units are in the axis labels. Generated by the problem's plot.py (licence: as the problem).\n")
        if thinned or len(rows) > MAX_CSV_ROWS:
            f.write(
                f"# Thinned for size: {len(thinned)} long series keep evenly spaced points (at most "
                f"{MAX_SERIES_POINTS} each); {min(len(rows), MAX_CSV_ROWS)} of {len(rows)} rows kept.\n"
            )
        used = dict.fromkeys(r[0] for r in rows[:MAX_CSV_ROWS])
        for title in used:
            f.write(f"# axes of '{title}': {axes_labels[title]}\n")
        w = csv.writer(f)
        w.writerow(["panel", "series", "x", "y", "z"])
        w.writerows([*r[:2], *(v if v == "" else f"{v:.6g}" for v in r[2:])] for r in rows[:MAX_CSV_ROWS])
    return _swap(tmp, path)


def frame_indices(n_steps: int, n_frames: int = MAX_FRAMES) -> list[int]:
    """Pick evenly spaced time steps so a GIF never has more than n_frames frames."""
    n_frames = 5 if fast_mode() else min(n_frames, MAX_FRAMES)
    n_frames = max(1, min(n_frames, n_steps))
    return [round(k * (n_steps - 1) / max(1, n_frames - 1)) for k in range(n_frames)]


def save_gif(fig: plt.Figure, update: Callable[[int], object], frames: list[int], path: Path, fps: int = 20) -> Path:
    """update(step) redraws the figure for one time step; frames lists the steps to render."""
    anim = FuncAnimation(fig, update, frames=frames, blit=False)
    tmp = _tmp_path(path)
    every = max(1, len(frames) // 50)  # about 2% steps for the web app's progress bar

    def tick(i: int, n: int) -> None:
        progress.update(1)
        if (i + 1) % every == 0 or i + 1 == n:
            report(i + 1, n, "frames")

    with bar(len(frames), "GIF frames") as progress:
        anim.save(tmp, writer=PillowWriter(fps=fps), dpi=80, progress_callback=tick)
    export_plot_data(fig, path)  # the numbers behind the final frame, for the Results page
    plt.close(fig)
    return _swap(tmp, path)  # swap in the finished file so a viewer never sees a half-written GIF


def save_png(fig: plt.Figure, path: Path) -> Path:
    tmp = _tmp_path(path)
    fig.savefig(tmp, dpi=100, bbox_inches="tight")
    export_plot_data(fig, path)
    plt.close(fig)
    return _swap(tmp, path)


def _swap(tmp: Path, path: Path, attempts: int = 25) -> Path:
    """Replace path with tmp, retrying while Windows reports the old file as in use (a server reading it)."""
    for _ in range(attempts - 1):
        try:
            return tmp.replace(path)
        except PermissionError:
            time.sleep(0.2)
    return tmp.replace(path)


def _tmp_path(path: Path) -> Path:
    path = Path(path)
    # Unique per process (two renders of one problem can overlap); same suffix so matplotlib picks the format.
    return path.with_name(f".{path.stem}.{os.getpid()}.tmp{path.suffix}")
